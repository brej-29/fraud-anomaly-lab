from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Dict, Optional

import joblib

from ml.models import MODEL_REGISTRY, BaseAnomalyModel  # type: ignore[import]
from ..core.logging import get_logger

logger = get_logger(__name__)


class ModelRegistry:
    """
    Registry for loading and accessing model artifacts.

    Responsibilities
    ----------------
    - Load preprocessor, model files, thresholds, and metadata from `ml/artifacts/`.
    - Provide a unified interface for the scoring service and API routes.
    - Degrade gracefully when artifacts are missing (e.g. in fresh environments).
    """

    def __init__(self, artifacts_dir: Path | None = None) -> None:
        self.artifacts_dir = artifacts_dir or Path("ml") / "artifacts"
        self._models: Dict[str, BaseAnomalyModel] = {}
        self.metadata: Dict[str, Any] = {}
        self.thresholds: Dict[str, float] = {}
        self.preprocessor: Any | None = None

    @property
    def loaded_models_count(self) -> int:
        return len(self._models)

    @property
    def feature_columns(self) -> list[str]:
        models_meta = self.metadata or {}
        # In metadata generated by ml.train_all, feature_columns are top-level.
        cols = models_meta.get("feature_columns") or self.metadata.get("feature_columns")
        if isinstance(cols, list):
            return cols
        return []

    @property
    def ensemble_config(self) -> Dict[str, Any]:
        """
        Return ensemble configuration from metadata, if present.

        The training pipeline stores the ensemble under the "ensemble" key in
        metadata["models"].
        """
        models_meta = self.metadata.get("models", {})
        ensemble_meta = models_meta.get("ensemble") if isinstance(models_meta, dict) else None
        return ensemble_meta or {}

    def load_all(self) -> None:
        """
        Load preprocessor, models, thresholds, and metadata from disk.

        Missing artifacts are logged and ignored so that the API can still start
        and return clear 503 errors when prediction is requested.
        """
        self._models.clear()
        self.metadata = {}
        self.thresholds = {}
        self.preprocessor = None

        artifacts_dir = self.artifacts_dir
        if not artifacts_dir.exists():
            logger.info("Artifacts directory %s does not exist; registry will be empty.", artifacts_dir)
            return

        # Load metadata.json if available.
        metadata_path = artifacts_dir / "metadata.json"
        if metadata_path.exists():
            try:
                with metadata_path.open("r", encoding="utf-8") as f:
                    self.metadata = json.load(f)
                logger.info("Loaded metadata from %s", metadata_path)
            except Exception as exc:  # noqa: BLE001
                logger.info("Failed to load metadata from %s: %s", metadata_path, exc)

        # Load thresholds.json if available.
        thresholds_path = artifacts_dir / "thresholds.json"
        if thresholds_path.exists():
            try:
                with thresholds_path.open("r", encoding="utf-8") as f:
                    raw = json.load(f)
                # Ensure we have a dict[str, float]-like mapping.
                self.thresholds = {k: float(v) for k, v in raw.items()}
                logger.info("Loaded thresholds from %s", thresholds_path)
            except Exception as exc:  # noqa: BLE001
                logger.info("Failed to load thresholds from %s: %s", thresholds_path, exc)

        # Load preprocessor if present.
        preproc_path = artifacts_dir / "preprocessor.joblib"
        if preproc_path.exists():
            try:
                self.preprocessor = joblib.load(preproc_path)
                logger.info("Loaded preprocessor from %s", preproc_path)
            except Exception as exc:  # noqa: BLE001
                logger.info("Failed to load preprocessor from %s: %s", preproc_path, exc)

        # Load individual model files based on MODEL_REGISTRY.
        models_section = self.metadata.get("models", {}) if isinstance(self.metadata, dict) else {}
        for name, wrapper_cls in MODEL_REGISTRY.items():
            model_info: Optional[Dict[str, Any]] = None
            if isinstance(models_section, dict):
                model_info = models_section.get(name)
            # Determine path: prefer artifact_path from metadata if available.
            if model_info and "artifact_path" in model_info:
                model_path = Path(model_info["artifact_path"])
            else:
                # Fallback to conventional naming.
                if name == "autoencoder":
                    model_path = artifacts_dir / "autoencoder.keras"
                else:
                    model_path = artifacts_dir / f"{name}.joblib"

            if not model_path.exists():
                continue

            try:
                model = wrapper_cls.load(model_path)
                self._models[name] = model
                logger.info("Loaded model '%s' from %s", name, model_path)
            except Exception as exc:  # noqa: BLE001
                logger.info("Failed to load model '%s' from %s: %s", name, model_path, exc)

        logger.info(
            "ModelRegistry initialized: %d models loaded, metadata=%s, thresholds=%s",
            self.loaded_models_count,
            bool(self.metadata),
            bool(self.thresholds),
        )

    def get_model(self, name: str) -> BaseAnomalyModel:
        """
        Retrieve a model by name, raising KeyError if it does not exist.
        """
        try:
            return self._models[name]
        except KeyError as exc:
            logger.error("Requested model '%s' not found in registry.", name)
            raise